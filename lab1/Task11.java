/*У Деда Мороза есть часы, которые в секундах показывают, 
сколько осталось до каждого Нового года. Так как Дед Мороз – человек уже в возрасте,
 то некоторые математические операции он быстро выполнять не в состоянии. 
 Помогите Деду Морозу определить, сколько полных дней, часов, минут и секунд осталось 
 до следующего Нового года, если известно сколько осталось секунд. Т. е. разложите время
  в секундах на полное количество дней, часов, минут и секунд. Выведите результат на консоль. 
Пример, как должен выглядеть вывод результата: 10 дней, 14 часов, 5 минут и 33 секунды 
 */

public class Task11 {
    public static void main(String[] args) {
        // Количество секунд до Нового года
        long totalSeconds = 900333; 
        
        // Вычисляем полные дни
        long days = totalSeconds / (24 * 3600);
        long remainingSeconds = totalSeconds % (24 * 3600);
    
        // Вычисляем полные часы
        long hours = remainingSeconds / 3600;
        remainingSeconds %= 3600;
        
        // Вычисляем полные минуты
        long minutes = remainingSeconds / 60;
        
        // Оставшиеся секунды
        long seconds = remainingSeconds % 60;
        
        System.out.println("\nДо Нового года осталось:");
        System.out.println(days + " дней, " + hours + " часов, " + 
                          minutes + " минут и " + seconds + " секунд");
    }
}