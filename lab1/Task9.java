/*Проверить, имеет ли число вещественную часть. Например, числа 3.14 и 2.5 – имеют вещественную часть, а числа 5.0 и 10.0 – нет.  */
public class Task9 {
    public static void main(String[] args) {
        // Тестируемые числа
        double[] numbers = {3.14, 2.5, 5.0, 10.0, 7.89};
        
        for (double num : numbers) {
            // Проверяем, имеет ли число вещественную часть
            // Если число равно своему целому значению - вещественной части нет
            if (num == (int)num) {
                System.out.println(num + " - не имеет вещественной части");
            } else {
                System.out.println(num + " - имеет вещественную часть");
            }
        }
    }
}